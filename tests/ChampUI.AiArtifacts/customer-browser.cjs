// Runs against the original Customers.razor in an Interactive Server Starter.
const { test, after } = require('node:test');
const assert = require('node:assert/strict');
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const base = process.env.CUSTOMER_TEST_URL;
if (!base) throw new Error('Set CUSTOMER_TEST_URL to the isolated Starter URL');
let browser;
after(async () => { if (browser) await browser.close(); });
test('original customer page: validation, cancel, save, search and dialog keyboard', async () => {
  browser = await chromium.launch({ headless: true });
  const page = await browser.newPage({ viewport: { width: 1280, height: 800 } });
  await page.goto(`${base}/customers`);
  await page.waitForFunction(() => {
    const button = document.querySelector('button[aria-label="Dark mode"]');
    return button && !button.disabled;
  });
  await page.getByRole('row').filter({ hasText: 'sara@example.com' }).waitFor();
  assert.equal(await page.locator('.ui-shell').getAttribute('data-theme'), 'light');
  await page.getByRole('button', { name: 'Review customer' }).waitFor();
  await page.getByRole('button', { name: 'Review customer' }).click();
  await page.getByText('Name is required.').waitFor();
  await page.getByText('Enter a valid email.').waitFor();
  await page.getByLabel('Full name').fill('Example Client');
  await page.getByLabel('Email', { exact: true }).fill('example-client@example.com');
  const open = page.getByRole('button', { name: 'Review customer' });
  await open.click();
  const dialog = page.getByRole('dialog');
  await dialog.getByText('Example Client').waitFor();
  await page.keyboard.press('Escape');
  await dialog.waitFor({ state: 'hidden' });
  assert.equal(await open.evaluate(e => e === document.activeElement), true, 'focus returns to trigger');
  assert.equal(await page.getByRole('row').filter({ hasText: 'Example Client' }).count(), 0);
  await open.click();
  await dialog.getByRole('button', { name: 'Cancel' }).click();
  assert.equal(await page.getByRole('row').filter({ hasText: 'Example Client' }).count(), 0);
  await open.click();
  await dialog.getByRole('button', { name: 'Confirm', exact: true }).click();
  await page.getByRole('row').filter({ hasText: 'Example Client' }).waitFor();
  await page.getByPlaceholder('Search customers…').fill('example-client@example.com');
  await page.getByRole('row').filter({ hasText: 'Example Client' }).waitFor();
  await page.getByRole('row').filter({ hasText: 'sara@example.com' }).waitFor({ state: 'hidden' });
  assert.equal(await page.getByRole('row').filter({ hasText: 'sara@example.com' }).count(), 0);
  await page.getByRole('button', { name: 'Dark mode' }).click();
  await page.getByRole('button', { name: 'Light mode' }).waitFor();
  assert.equal(await page.locator('.ui-shell').getAttribute('data-theme'), 'dark');
  await page.getByRole('button', { name: 'العربية' }).click();
  await page.getByRole('heading', { name: 'إدارة العملاء' }).waitFor();
  await page.waitForFunction(() => document.documentElement.dir === 'rtl');
  await page.setViewportSize({ width: 390, height: 844 });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true, 'no horizontal overflow');
  await page.getByRole('button', { name: 'English' }).click();
  await page.waitForFunction(() => document.documentElement.dir === 'ltr');
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true, 'no LTR horizontal overflow');
  await page.close();
});
